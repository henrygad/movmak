-- The official organization website replaces the user-facing slug input.
-- Slugs remain internal stable identifiers and are generated by the database.
drop function public.create_organization_with_admin(text, text, text);
create function public.create_organization_with_admin(
  p_name text,
  p_website_url text,
  p_timezone text default 'Africa/Lagos'
)
returns table (organization_id uuid, membership_id uuid)
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_user_id uuid := auth.uid();
  created_organization_id uuid;
  created_membership_id uuid;
  generated_slug text;
begin
  if actor_user_id is null then
    raise exception 'authentication is required' using errcode = '42501';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(actor_user_id::text, 0));
  if exists (select 1 from public.organization_memberships where user_id = actor_user_id)
    or exists (
      select 1 from private.organization_membership_requests
      where user_id = actor_user_id and status = 'pending'
    ) then
    raise exception 'organization onboarding is not available';
  end if;

  p_name := pg_catalog.btrim(p_name);
  p_website_url := pg_catalog.btrim(p_website_url);
  p_timezone := pg_catalog.btrim(p_timezone);
  if p_name is null or pg_catalog.char_length(p_name) not between 2 and 160 then
    raise exception 'organization name is invalid';
  end if;
  if p_website_url is null or p_website_url !~* '^https?://[^[:space:]/]+\.[^[:space:]]+$'
    or pg_catalog.char_length(p_website_url) > 2048 then
    raise exception 'organization website is invalid';
  end if;
  if p_timezone is null or not exists (
    select 1 from pg_catalog.pg_timezone_names where name = p_timezone
  ) then
    raise exception 'organization timezone is invalid';
  end if;

  generated_slug := pg_catalog.btrim(
    pg_catalog.regexp_replace(pg_catalog.lower(p_name), '[^a-z0-9]+', '-', 'g'),
    '-'
  );
  if pg_catalog.char_length(generated_slug) < 2 then generated_slug := 'organization'; end if;
  generated_slug := pg_catalog.left(generated_slug, 90) || '-' || pg_catalog.substr(pg_catalog.gen_random_uuid()::text, 1, 8);

  insert into public.organizations (name, slug, website_url, timezone, created_by_user_id)
  values (p_name, generated_slug, p_website_url, p_timezone, actor_user_id)
  returning id into created_organization_id;

  insert into public.organization_memberships (
    organization_id, user_id, role, status, created_by_user_id
  ) values (
    created_organization_id, actor_user_id, 'admin', 'active', actor_user_id
  ) returning id into created_membership_id;

  return query select created_organization_id, created_membership_id;
end;
$$;

revoke all on function public.create_organization_with_admin(text, text, text)
  from public, anon, service_role;
grant execute on function public.create_organization_with_admin(text, text, text)
  to authenticated;

-- Roles are immutable for an account. Administrators may change status only.
create or replace function public.manage_organization_membership(
  p_organization_id uuid,
  p_membership_id uuid,
  p_role public.organization_role,
  p_status public.membership_status
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare actor record; target record;
begin
  select id, user_id into actor
  from public.organization_memberships
  where organization_id = p_organization_id and user_id = (select auth.uid())
    and role = 'admin' and status = 'active'
  for update;
  if not found then raise exception 'membership management is not permitted' using errcode = '42501'; end if;

  select id, user_id, role, status into target
  from public.organization_memberships
  where id = p_membership_id and organization_id = p_organization_id
  for update;
  if not found then raise exception 'membership is not available'; end if;
  if target.user_id = actor.user_id then raise exception 'administrators cannot change their own membership'; end if;
  if p_role is distinct from target.role then raise exception 'membership roles cannot be changed'; end if;
  if target.role = 'admin' and target.status = 'active' and p_status <> 'active'
    and not exists (
      select 1 from public.organization_memberships other
      where other.organization_id = p_organization_id and other.id <> target.id
        and other.role = 'admin' and other.status = 'active'
    ) then
    raise exception 'the organization must retain an active administrator';
  end if;

  update public.organization_memberships
  set status = p_status,
      revoked_at = case when p_status = 'revoked' then coalesce(revoked_at, clock_timestamp()) else null end
  where id = target.id;
  return true;
end;
$$;

create function public.update_organization_settings(p_website_url text, p_logo_url text)
returns boolean
language plpgsql security definer set search_path = '' as $$
declare actor_organization_id uuid;
begin
  select organization_id into actor_organization_id
  from public.organization_memberships
  where user_id = (select auth.uid()) and role = 'admin' and status = 'active';
  if not found then raise exception 'organization settings are not permitted' using errcode = '42501'; end if;
  p_website_url := pg_catalog.btrim(p_website_url);
  if p_website_url is null or p_website_url !~* '^https?://[^[:space:]/]+\.[^[:space:]]+$'
    or pg_catalog.char_length(p_website_url) > 2048 then
    raise exception 'organization website is invalid';
  end if;
  if p_logo_url is not null and (
    pg_catalog.char_length(p_logo_url) > 2048
    or p_logo_url !~ '^https://'
    or p_logo_url not like '%/storage/v1/object/public/organization-logos/' || actor_organization_id::text || '/logo'
  ) then raise exception 'organization logo URL is invalid'; end if;
  update public.organizations
  set website_url = p_website_url, logo_url = p_logo_url
  where id = actor_organization_id;
  return true;
end;
$$;

revoke all on function public.update_organization_settings(text, text) from public, anon, service_role;
grant execute on function public.update_organization_settings(text, text) to authenticated;

-- Host credentials are available only after the host supplies operational
-- contact details needed by authorized administrators and gate staff.
create or replace function public.issue_host_credentials(
  p_invitation_token_hash bytea,
  p_host_code_hash bytea
)
returns table (invitation_expires_at timestamptz, host_code_expires_at timestamptz)
language plpgsql security definer set search_path = '' as $$
declare actor_membership record; issued_at timestamptz;
begin
  if (select auth.uid()) is null then raise exception 'authentication is required'; end if;
  if p_invitation_token_hash is null or p_host_code_hash is null
    or octet_length(p_invitation_token_hash) <> 32 or octet_length(p_host_code_hash) <> 32 then
    raise exception 'credential input is invalid';
  end if;

  select membership.id, membership.organization_id into actor_membership
  from public.organization_memberships membership
  join public.user_profiles profile on profile.user_id = membership.user_id
    and profile.full_name is not null and profile.phone is not null and profile.address is not null
  where membership.user_id = (select auth.uid()) and membership.status = 'active' and membership.role = 'host'
  for update of membership;
  if not found then raise exception 'complete your host profile before issuing credentials'; end if;

  issued_at := clock_timestamp();
  if (select count(*) from public.invitation_credentials where host_membership_id = actor_membership.id and created_at > issued_at - interval '1 minute') >= 5
    or (select count(*) from public.invitation_credentials where host_membership_id = actor_membership.id and created_at > issued_at - interval '1 hour') >= 60 then
    raise exception 'host credential issuance is rate limited';
  end if;
  update public.invitation_credentials set revoked_at = issued_at
    where organization_id = actor_membership.organization_id and host_membership_id = actor_membership.id
      and consumed_at is null and revoked_at is null and expires_at > issued_at;
  update public.host_verification_codes set revoked_at = issued_at
    where organization_id = actor_membership.organization_id and host_membership_id = actor_membership.id
      and revoked_at is null and expires_at > issued_at;
  insert into public.invitation_credentials (organization_id, host_membership_id, token_hash, valid_from, expires_at, created_by_membership_id, created_at)
    values (actor_membership.organization_id, actor_membership.id, p_invitation_token_hash, issued_at, issued_at + interval '5 minutes', actor_membership.id, issued_at);
  insert into public.host_verification_codes (organization_id, host_membership_id, code_hash, valid_from, expires_at, created_by_membership_id, created_at)
    values (actor_membership.organization_id, actor_membership.id, p_host_code_hash, issued_at, issued_at + interval '5 minutes', actor_membership.id, issued_at);
  return query select issued_at + interval '5 minutes', issued_at + interval '5 minutes';
end;
$$;

-- Gate views include host contact/address only for an active security member
-- in the same organization. The public visitor flow never receives them.
drop function public.preview_visit_by_qr(bytea);
create function public.preview_visit_by_qr(p_qr_token_hash bytea)
returns table (
  visit_id uuid, visit_reference text, visitor_name text, visitor_phone text,
  host_name text, host_phone text, host_address text, purpose text,
  group_size smallint, visit_status public.visit_status
)
language plpgsql stable security definer set search_path = '' as $$
begin
  if p_qr_token_hash is null or octet_length(p_qr_token_hash) <> 32 then return; end if;
  return query
  select visit.id, visit.visit_reference, visitor.full_name, visitor.phone,
    coalesce(profile.full_name, 'Organization host'), profile.phone, profile.address,
    visit.purpose, visit.group_size, visit.status
  from public.visit_qr_credentials qr
  join public.visits visit on visit.id = qr.visit_id and visit.organization_id = qr.organization_id
  join public.visitors visitor on visitor.id = visit.visitor_id and visitor.organization_id = visit.organization_id
  join public.organization_memberships actor on actor.organization_id = visit.organization_id
    and actor.user_id = (select auth.uid()) and actor.status = 'active' and actor.role = 'security'
  join public.organization_memberships host on host.id = visit.host_membership_id and host.organization_id = visit.organization_id
  left join public.user_profiles profile on profile.user_id = host.user_id
  where qr.token_hash = p_qr_token_hash and qr.revoked_at is null
    and (qr.expires_at is null or qr.expires_at > clock_timestamp())
    and visit.status in ('expected', 'inside');
end;
$$;

drop function public.get_currently_inside();
create function public.get_currently_inside()
returns table (
  visit_id uuid, visit_reference text, visitor_name text, host_name text,
  host_phone text, host_address text, purpose text, group_size smallint,
  checked_in_at timestamptz
)
language sql stable security definer set search_path = '' as $$
  select visit.id, visit.visit_reference, visitor.full_name,
    coalesce(profile.full_name, 'Organization host'), profile.phone, profile.address,
    visit.purpose, visit.group_size, visit.checked_in_at
  from public.organization_memberships actor
  join public.visits visit on visit.organization_id = actor.organization_id and visit.status = 'inside'
  join public.visitors visitor on visitor.id = visit.visitor_id and visitor.organization_id = visit.organization_id
  join public.organization_memberships host on host.id = visit.host_membership_id and host.organization_id = visit.organization_id
  left join public.user_profiles profile on profile.user_id = host.user_id
  where actor.user_id = (select auth.uid()) and actor.status = 'active' and actor.role = 'security'
  order by visit.checked_in_at desc;
$$;

create function public.update_visit_companions(p_visit_id uuid, p_companion_count smallint)
returns smallint
language plpgsql security definer set search_path = '' as $$
declare actor record; target record; new_group_size smallint;
begin
  if p_companion_count is null or p_companion_count not between 0 and 99 then
    raise exception 'companion count is invalid';
  end if;
  select id, organization_id into actor from public.organization_memberships
  where user_id = (select auth.uid()) and status = 'active' and role = 'security'
  for update;
  if not found then raise exception 'gate operation is not permitted' using errcode = '42501'; end if;
  select id, group_size, status into target from public.visits
  where id = p_visit_id and organization_id = actor.organization_id for update;
  if not found or target.status not in ('expected', 'inside') then
    raise exception 'visit is not available for a companion update';
  end if;
  new_group_size := p_companion_count + 1;
  if target.group_size <> new_group_size then
    update public.visits set group_size = new_group_size where id = target.id;
    perform private.write_audit_event(
      actor.organization_id, 'visit.companions_updated', 'visits', target.id,
      'authenticated_user', actor.id,
      jsonb_build_object(
        'previous_companion_count', target.group_size - 1,
        'companion_count', p_companion_count,
        'previous_group_size', target.group_size,
        'group_size', new_group_size
      )
    );
  end if;
  return new_group_size;
end;
$$;

